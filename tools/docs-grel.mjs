// Write docs/src/grel.md from OpenRefine's own function descriptions (ui/src/grel-docs.json) and
// OxRefine's function list (crates/ox-core/src/grel/funcs.rs):  node tools/docs-grel.mjs
import { readFileSync, writeFileSync } from "node:fs"

const root = new URL("../", import.meta.url)
const docs = JSON.parse(readFileSync(new URL("ui/src/grel-docs.json", root), "utf8"))
const src = readFileSync(new URL("crates/ox-core/src/grel/funcs.rs", root), "utf8")
const list = (name) => new Set([...src.match(new RegExp(`pub const ${name}: &\\[&str\\] = &\\[([\\s\\S]*?)\\];`))[1].matchAll(/"(\w+)"/g)].map((m) => m[1]))
const functions = list("FUNCTIONS")
const controls = list("CONTROLS")
// supported, but not like OpenRefine yet
const partly = { detectLanguage: "returns an error for now, because OxRefine has no language-identification model yet" }

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n+/g, " ")
const entry = (name, d, have) => {
  const sig = `${name}(${d.params ?? ""})`
  const note = !have ? "\n\n> **Not in OxRefine yet.**" : Object.hasOwn(partly, name) ? `\n\n> **In OxRefine:** ${partly[name]}.` : ""
  return `### ${name}\n\n\`${sig}\` → ${d.returns ?? "any"}\n\n${esc(d.description)}${note}\n`
}

const fnNames = Object.keys(docs.functions).sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }))
const ctlNames = Object.keys(docs.controls).sort()
const missing = fnNames.filter((n) => !functions.has(n))

const out = `<!-- Generated by tools/docs-grel.mjs from OpenRefine 3.10.1's function descriptions (BSD-3-Clause). Don't edit by hand. -->

# GREL functions

GREL, the General Refine Expression Language, is the expression language used in **Transform…**, **Add column based on this…**, custom facets and templates. OxRefine runs it like OpenRefine 3.10.1: the same functions, controls, operators, errors and number formatting. ${fnNames.length - missing.length} of OpenRefine's ${fnNames.length} functions and all ${ctlNames.length} controls are available${missing.length ? `; not yet: ${missing.map((n) => `\`${n}\``).join(", ")}` : ""}.

The descriptions below are OpenRefine's own, from OpenRefine 3.10.1.

## Variables

| Variable | Meaning |
|---|---|
| \`value\` | The value of the current cell |
| \`cell\` | The current cell: \`cell.value\`, and \`cell.recon\` for its reconciliation data |
| \`cells\` | The row's cells by column name: \`cells["Name"].value\` |
| \`row\` | The current row: \`row.index\`, \`row.starred\`, \`row.flagged\`, \`row.cells\` |
| \`rowIndex\` | The row's position, from 0 |
| \`record\` | Not in OxRefine yet. In OpenRefine, the current record in records mode |

## Operators

\`+ - * / %\` for numbers (\`+\` also joins text), \`== != < <= > >=\` for comparisons, \`and(…)\`, \`or(…)\` and \`not(…)\` for logic, \`[index]\` and \`[from, to]\` for elements and slices of text and arrays, and \`.\` to call a function on a value: \`value.trim()\` is \`trim(value)\`.

## Controls

${ctlNames.map((n) => entry(n, docs.controls[n], controls.has(n))).join("\n")}
## Functions

${fnNames.map((n) => entry(n, docs.functions[n], functions.has(n))).join("\n")}`
writeFileSync(new URL("docs/src/grel.md", root), out)
console.log(`docs/src/grel.md: ${ctlNames.length} controls, ${fnNames.length} functions, missing: ${missing.join(", ") || "none"}`)
